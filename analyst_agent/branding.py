"""Who a report comes from: the organisation, the author, a notice such as "internal use only", and a logo.

The defaults are in branding/branding.json and branding/logo.png next to the app: edit the file or replace the
logo to change them for every report. REPORT_ORGANISATION, REPORT_AUTHOR, REPORT_NOTICE and REPORT_LOGO (a
file path) override them, and the sidebar's Report branding settings change them for one session.
"""

from __future__ import annotations

import base64
import json
import os
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

BRANDING_DIR = Path(__file__).resolve().parent.parent / "branding"
MAX_LOGO_BYTES = 2 * 1024 * 1024


@dataclass
class Branding:
    organisation: str = ""
    author: str = ""
    notice: str = ""  # e.g. "For internal use only."
    logo: bytes | None = None  # PNG or JPEG
    show_logo: bool = True
    mention_ai: bool = True  # name the language model in reports (the shipped defaults turn it off)

    @property
    def credit(self) -> str:
        """'Generated at Apollo Tyres Ltd by Dr ...', as far as organisation and author are set."""
        org, author = self.organisation.strip(), self.author.strip()
        if org and author:
            return f"Generated at {org} by {author}"
        return f"Generated by {author}" if author else f"Generated at {org}" if org else ""

    def credit_on(self, when: datetime | None = None) -> str:
        """The credit with the date, for a report's header."""
        credit = self.credit
        date = (when or datetime.now()).strftime("%d %b %Y")
        return f"{credit} on {date}" if credit else ""

    @property
    def logo_shown(self) -> bytes | None:
        return self.logo if self.show_logo and self.logo else None

    @property
    def empty(self) -> bool:
        return not (self.credit or self.notice.strip() or self.logo_shown)

    def logo_data_uri(self) -> str:
        logo = self.logo_shown
        if not logo:
            return ""
        kind = "image/jpeg" if logo[:3] == b"\xff\xd8\xff" else "image/png"
        return f"data:{kind};base64,{base64.b64encode(logo).decode('ascii')}"

    def markdown_lines(self) -> list[str]:
        """The credit and notice as Markdown lines for a text report ([] when neither is set)."""
        lines = [f"- {self.credit_on()}"] if self.credit else []
        if self.notice.strip():
            lines.append(f"- **{self.notice.strip()}**")
        return lines


def _read_logo(path: Path) -> bytes | None:
    try:
        data = path.read_bytes()
    except OSError:
        return None
    if len(data) > MAX_LOGO_BYTES or not (data.startswith(b"\x89PNG") or data[:3] == b"\xff\xd8\xff"):
        return None  # only PNG and JPEG, as they are embedded in the reports
    return data


def load_branding(folder: Path | None = None) -> Branding:
    """The default branding: branding/branding.json and branding/logo.png, then the REPORT_* variables."""
    folder = folder or BRANDING_DIR
    settings: dict = {}
    try:
        loaded = json.loads((folder / "branding.json").read_text(encoding="utf-8"))
        settings = loaded if isinstance(loaded, dict) else {}
    except (OSError, ValueError):
        pass
    logo_path = os.environ.get("REPORT_LOGO") or str(folder / str(settings.get("logo") or "logo.png"))
    return Branding(
        organisation=os.environ.get("REPORT_ORGANISATION", str(settings.get("organisation", ""))),
        author=os.environ.get("REPORT_AUTHOR", str(settings.get("author", ""))),
        notice=os.environ.get("REPORT_NOTICE", str(settings.get("notice", ""))),
        logo=_read_logo(Path(logo_path)),
        mention_ai=_flag(os.environ.get("REPORT_MENTION_AI"), settings.get("mention_ai", True)),
    )


def _flag(value: str | None, default) -> bool:
    if value is None:
        return bool(default)
    return value.strip().lower() in ("1", "true", "yes", "on")
