PNG = (BRANDING_DIR / "logo.png").read_bytes()


def test_the_app_ships_its_defaults(monkeypatch):
    for name in ("REPORT_ORGANISATION", "REPORT_AUTHOR", "REPORT_NOTICE", "REPORT_LOGO"):
        monkeypatch.delenv(name, raising=False)
    b = load_branding()
    assert b.organisation == "Apollo Tyres Ltd" and b.author == "Dr Shreeharsha Ramaswamy"
    assert b.credit == "Generated at Apollo Tyres Ltd by Dr Shreeharsha Ramaswamy"
    assert b.notice.startswith("For internal use only") and b.logo.startswith(b"\x89PNG")


def test_variables_and_folders(tmp_path, monkeypatch):
    (tmp_path / "branding.json").write_text(json.dumps({"organisation": "Org", "author": "A", "notice": "N"}))
    (tmp_path / "logo.png").write_bytes(b"not an image")  # not PNG or JPEG: no logo
    b = load_branding(tmp_path)
    assert (b.organisation, b.author, b.notice, b.logo) == ("Org", "A", "N", None)
    logo = tmp_path / "other.png"
    logo.write_bytes(PNG)
    monkeypatch.setenv("REPORT_AUTHOR", "B")
    monkeypatch.setenv("REPORT_LOGO", str(logo))
    b = load_branding(tmp_path)
    assert b.author == "B" and b.logo == PNG
    assert load_branding(tmp_path / "missing").organisation == ""
    assert Branding().empty and Branding(author="A").credit == "Generated by A"
    assert Branding(organisation="O").credit == "Generated at O"
    assert Branding(logo=PNG, show_logo=False).empty


def test_html_report_header_and_footer():
    b = Branding(organisation="Apollo Tyres Ltd", author="Dr Shreeharsha Ramaswamy",
                 notice="For internal use only.", logo=PNG)
    page = report_html([rb.heading("Report", 1)], "Report", branding=b).decode()
    assert '<header class="brand"><img alt="Apollo Tyres Ltd" src="data:image/png;base64,' in page
    assert "Generated at Apollo Tyres Ltd by Dr Shreeharsha Ramaswamy on " in page
    assert page.count("For internal use only.") == 2  # at the top and in the footer that repeats when printed
    assert '<meta name="author" content="Dr Shreeharsha Ramaswamy">' in page
    assert page.index('class="brand"') < page.index("<h1")
    # Printed, the footer is a table footer row: browsers repeat it on every page and keep room for it.
    assert '<table class="pagewrap"><tbody><tr><td>' in page and '<tfoot><tr><td><footer class="brand-foot">' in page
    plain = report_html([rb.heading("Report", 1)], "Report").decode()
    assert 'class="brand"' not in plain and "brand-foot" not in plain and "pagewrap" not in plain
    no_logo = report_html([rb.heading("R", 1)], "R", branding=Branding(notice="Internal", logo=PNG,
                                                                      show_logo=False)).decode()
    assert "<img" not in no_logo and "Internal" in no_logo


def test_workbook_contents_sheet():
    from openpyxl import load_workbook

    b = Branding(organisation="Apollo Tyres Ltd", author="Dr Shreeharsha Ramaswamy", notice="Internal use only",
                 logo=PNG)
    data = report_workbook([rb.heading("S"), rb.table(pd.DataFrame({"a": [1]}), title="T")], "Title", b)
    book = load_workbook(io.BytesIO(data))
    ws = book["Contents"]
    assert ws["A1"].value == "Title" and ws["A2"].value.startswith("Generated at Apollo Tyres Ltd by Dr")
    assert ws["A2"].value.endswith("· Internal use only") and len(ws._images) == 1
    assert book.properties.creator == "Dr Shreeharsha Ramaswamy"
    assert pd.read_excel(io.BytesIO(data), skiprows=2)["Sheet"].tolist() == ["01 T"]  # the table stays put


