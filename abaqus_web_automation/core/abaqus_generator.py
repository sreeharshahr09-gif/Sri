def _open_csv(path):
    # Abaqus ships Python 2 up to the 2023 release and Python 3 from 2024.
    # Python 2 needs binary mode and Python 3 needs newline='' -- without this
    # every CSV written on Windows gains a blank line between rows.
    try:
        return open(path, 'w', newline='')
    except TypeError:
        return open(path, 'wb')


def _find_region(odb, name):
    if not name: return None
    candidates = [name, name.upper(), 'N_' + name, ('N_' + name).upper()]
    ra = odb.rootAssembly
    for n in candidates:
        if n in ra.nodeSets: return ra.nodeSets[n]
        if n in ra.elementSets: return ra.elementSets[n]
    for inst in ra.instances.values():
        for n in candidates:
            if n in inst.nodeSets: return inst.nodeSets[n]
            if n in inst.elementSets: return inst.elementSets[n]
    return None


def _const_position(name):
    return {{'NODAL': NODAL, 'ELEMENT_NODAL': ELEMENT_NODAL,
            'CENTROID': CENTROID, 'INTEGRATION_POINT': INTEGRATION_POINT}}.get(name)


